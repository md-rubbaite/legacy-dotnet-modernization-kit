using System.Globalization;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace Modernize;

public static class Reports
{
    private static readonly JsonSerializerOptions Json = new() { WriteIndented = true, Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping };

    public static string Markdown(ScanResult result, int maxLocationsPerRule = 10)
    {
        ArgumentNullException.ThrowIfNull(result);
        var inv = CultureInfo.InvariantCulture;
        var sb = new StringBuilder();
        sb.AppendLine("# .NET modernization assessment").AppendLine();
        sb.AppendLine(inv, $"- Scanned: `{Path.GetFileName(result.Root)}`, {result.Projects.Count} projects, {result.FilesScanned} files");
        sb.AppendLine(inv, $"- As of: {result.AsOf:yyyy-MM-dd} (support dates checked {SupportPolicy.CheckedOn}; current LTS {SupportPolicy.CurrentLts}, supported until {SupportPolicy.CurrentLtsEnds:yyyy-MM-dd})");
        sb.AppendLine(inv, $"- Findings: {result.Count(Severity.Blocker)} blocker, {result.Findings.Count(f => f.Rule.Severity == Severity.High)} high, {result.Findings.Count(f => f.Rule.Severity == Severity.Medium)} medium, {result.Findings.Count(f => f.Rule.Severity == Severity.Low)} low");
        sb.AppendLine();

        sb.AppendLine("## Projects and migration order").AppendLine();
        sb.AppendLine("| Wave | Project | Kind | Target now | Support | Readiness | Effort | Recommended target |");
        sb.AppendLine("|---|---|---|---|---|---|---|---|");
        foreach (var a in result.Projects)
        {
            var tfms = string.Join(", ", a.Project.TargetFrameworks.Select(SupportPolicy.Normalize));
            var support = string.Join("; ", a.Project.TargetFrameworks.Select(t => SupportPolicy.Describe(t, result.AsOf)).Distinct());
            sb.AppendLine(inv, $"| {a.Wave} | {a.Project.Name} | {a.Project.Kind} | {tfms} | {support} | {a.Readiness}/100 | {a.Size} ({a.EffortPoints} pts) | {a.RecommendedTarget} |");
        }
        sb.AppendLine().AppendLine("Readiness: 100 minus 25 per blocker rule, 10 per high, 4 per medium, 1 per low. Effort points are relative, for sequencing and sizing; calibrate them against your first migrated project.").AppendLine();

        sb.AppendLine("## Plan").AppendLine();
        foreach (var wave in result.Projects.GroupBy(a => a.Wave))
        {
            sb.AppendLine(inv, $"### Wave {wave.Key}").AppendLine();
            foreach (var a in wave)
            {
                if (a.Actions.Count == 0)
                {
                    sb.AppendLine(inv, $"- **{a.Project.Name}**: nothing to do.");
                    continue;
                }
                sb.AppendLine(inv, $"- **{a.Project.Name}** → {a.RecommendedTarget}");
                foreach (var action in a.Actions) sb.AppendLine(inv, $"  - {action}");
            }
            sb.AppendLine();
        }

        sb.AppendLine("## Findings").AppendLine();
        foreach (var group in result.Findings.GroupBy(f => f.Rule))
        {
            var r = group.Key;
            sb.AppendLine(inv, $"### {r.Id} {r.Title} ({r.Severity}, {group.Count()})").AppendLine();
            sb.AppendLine(r.Guidance).AppendLine();
            foreach (var f in group.Take(maxLocationsPerRule)) sb.AppendLine(inv, $"- `{f.File}:{f.Line}` {Escape(f.Evidence)}");
            if (group.Count() > maxLocationsPerRule) sb.AppendLine(inv, $"- … and {group.Count() - maxLocationsPerRule} more (see the JSON or SARIF report)");
            sb.AppendLine();
        }
        sb.AppendLine("_Generated by legacy-dotnet-modernization-kit. Static analysis finds patterns, not every behaviour change; run your tests on the new target._");
        return sb.ToString();
    }

    public static string JsonReport(ScanResult result)
    {
        ArgumentNullException.ThrowIfNull(result);
        var o = new JsonObject
        {
            ["tool"] = "legacy-dotnet-modernization-kit",
            ["asOf"] = result.AsOf.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture),
            ["supportDatesCheckedOn"] = SupportPolicy.CheckedOn,
            ["summary"] = new JsonObject
            {
                ["projects"] = result.Projects.Count,
                ["files"] = result.FilesScanned,
                ["blocker"] = result.Findings.Count(f => f.Rule.Severity == Severity.Blocker),
                ["high"] = result.Findings.Count(f => f.Rule.Severity == Severity.High),
                ["medium"] = result.Findings.Count(f => f.Rule.Severity == Severity.Medium),
                ["low"] = result.Findings.Count(f => f.Rule.Severity == Severity.Low),
            },
            ["projects"] = new JsonArray(result.Projects.Select(a => (JsonNode)new JsonObject
            {
                ["name"] = a.Project.Name,
                ["file"] = Path.GetRelativePath(result.Root, a.Project.File).Replace('\\', '/'),
                ["kind"] = a.Project.Kind.ToString(),
                ["sdkStyle"] = a.Project.SdkStyle,
                ["targetFrameworks"] = new JsonArray(a.Project.TargetFrameworks.Select(t => (JsonNode)SupportPolicy.Normalize(t)).ToArray()),
                ["wave"] = a.Wave,
                ["readiness"] = a.Readiness,
                ["effortPoints"] = a.EffortPoints,
                ["size"] = a.Size,
                ["recommendedTarget"] = a.RecommendedTarget,
                ["actions"] = new JsonArray(a.Actions.Select(x => (JsonNode)x).ToArray()),
            }).ToArray()),
            ["findings"] = new JsonArray(result.Findings.Select(f => (JsonNode)new JsonObject
            {
                ["rule"] = f.Rule.Id,
                ["severity"] = f.Rule.Severity.ToString().ToLowerInvariant(),
                ["title"] = f.Rule.Title,
                ["file"] = f.File,
                ["line"] = f.Line,
                ["project"] = f.Project,
                ["evidence"] = f.Evidence,
            }).ToArray()),
        };
        return o.ToJsonString(Json);
    }

    /// <summary>SARIF 2.1.0, for GitHub code scanning and Azure DevOps.</summary>
    public static string Sarif(ScanResult result)
    {
        ArgumentNullException.ThrowIfNull(result);
        var used = result.Findings.Select(f => f.Rule).Distinct().OrderBy(r => r.Id, StringComparer.Ordinal).ToList();
        var index = used.Select((r, i) => (r, i)).ToDictionary(x => x.r.Id, x => x.i, StringComparer.Ordinal);
        static string Level(Severity s) => s >= Severity.High ? "error" : s == Severity.Medium ? "warning" : "note";
        var sarif = new JsonObject
        {
            ["$schema"] = "https://json.schemastore.org/sarif-2.1.0.json",
            ["version"] = "2.1.0",
            ["runs"] = new JsonArray(new JsonObject
            {
                ["tool"] = new JsonObject
                {
                    ["driver"] = new JsonObject
                    {
                        ["name"] = "legacy-dotnet-modernization-kit",
                        ["informationUri"] = "https://github.com/md-rubbaite/legacy-dotnet-modernization-kit",
                        ["version"] = "1.0.0",
                        ["rules"] = new JsonArray(used.Select(r => (JsonNode)new JsonObject
                        {
                            ["id"] = r.Id,
                            ["name"] = r.Title,
                            ["shortDescription"] = new JsonObject { ["text"] = r.Title },
                            ["help"] = new JsonObject { ["text"] = r.Guidance },
                            ["defaultConfiguration"] = new JsonObject { ["level"] = Level(r.Severity) },
                            ["properties"] = new JsonObject { ["category"] = r.Category, ["severity"] = r.Severity.ToString().ToLowerInvariant() },
                        }).ToArray()),
                    },
                },
                ["results"] = new JsonArray(result.Findings.Select(f => (JsonNode)new JsonObject
                {
                    ["ruleId"] = f.Rule.Id,
                    ["ruleIndex"] = index[f.Rule.Id],
                    ["level"] = Level(f.Rule.Severity),
                    ["message"] = new JsonObject { ["text"] = $"{f.Rule.Title}: {f.Evidence}" },
                    ["locations"] = new JsonArray(new JsonObject
                    {
                        ["physicalLocation"] = new JsonObject
                        {
                            ["artifactLocation"] = new JsonObject { ["uri"] = Uri.EscapeDataString(f.File).Replace("%2F", "/", StringComparison.Ordinal) },
                            ["region"] = new JsonObject { ["startLine"] = f.Line },
                        },
                    }),
                }).ToArray()),
            }),
        };
        return sarif.ToJsonString(Json);
    }

    public static string RulesMarkdown()
    {
        var sb = new StringBuilder("| Id | Rule | Severity | Category | Guidance |\n|---|---|---|---|---|\n");
        foreach (var r in Rules.All) sb.Append(CultureInfo.InvariantCulture, $"| {r.Id} | {r.Title} | {r.Severity} | {r.Category} | {Escape(r.Guidance)} |\n");
        return sb.ToString();
    }

    private static string Escape(string s) => s.Replace("|", "\\|", StringComparison.Ordinal).Replace("<", "&lt;", StringComparison.Ordinal);
}
